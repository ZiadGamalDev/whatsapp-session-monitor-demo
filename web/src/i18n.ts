export type Key = keyof (typeof dict)['ar'];

function initialLang(): Lang {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl === 'en' || fromUrl === 'ar') return fromUrl;
  try {
    const saved = localStorage.getItem('wsm.lang');
    if (saved === 'en' || saved === 'ar') return saved;
  } catch {
    /* storage unavailable */
  }
  return 'ar';
}

export const lang = ref<Lang>(initialLang());

export function applyLang(l: Lang): void {
  lang.value = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  document.title = t('docTitle');
  try {
    localStorage.setItem('wsm.lang', l);
  } catch {
    /* ignore */
  }
}

export function t(key: Key | string, vars: Record<string, string | number> = {}): string {
  const table = dict[lang.value] as Record<string, string>;
  const raw = table[key] ?? (dict.en as Record<string, string>)[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? `{${k}}` : String(vars[k])));
}

export function has(key: string): boolean {
  return key in dict[lang.value];
}

export function arrow(): string {
  return lang.value === 'ar' ? '←' : '→';
}

export function duration(ms: number | null | undefined, precise = false): string {
  if (ms === null || ms === undefined) return t('dash');
  const en = lang.value === 'en';
  const unit = (n: number | string, u: 's' | 'm' | 'h') => (en ? `${n}${u}` : `${n} ${t(`unit.${u}`)}`);
  if (precise && ms < 10_000) return unit((ms / 1000).toFixed(1), 's');
  const s = Math.floor(ms / 1000);
  if (s < 60) return unit(s, 's');
  const m = Math.floor(s / 60);
  if (m < 60) return s % 60 ? `${unit(m, 'm')} ${unit(s % 60, 's')}` : unit(m, 'm');
  const h = Math.floor(m / 60);
  return m % 60 ? `${unit(h, 'h')} ${unit(m % 60, 'm')}` : unit(h, 'h');
}

export function clock(at: number | null | undefined): string {
  if (!at) return t('dash');
  return new Date(at).toLocaleTimeString(lang.value === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', {
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
    timeZone: 'UTC',
  });
}

export function label(raw: string): string {
  return raw.replace(/^Line /, `${t('line')} `);
}

/** "Demo customer 07" -> "عميل تجريبي 07" in Arabic. */
export function customerName(raw: string): string {
  return raw.replace(/^Demo customer /, `${t('inbox.customer')} `);
}

/** Short relative day/time for message lists (UTC, like the rest of the UI). */
export function stamp(at: number, now: number): string {
  const d = new Date(at).toISOString().slice(0, 10);
  const today = new Date(now).toISOString().slice(0, 10);
  if (d === today) return clock(at).slice(0, 5);
  return new Date(at).toLocaleDateString(lang.value === 'ar' ? 'ar-EG-u-nu-latn' : 'en-GB', {
    day: '2-digit',
    month: 'short',
    timeZone: 'UTC',
  });
}

/** "131026 Message undeliverable" -> code + translated label. */
export function reasonCode(reason: string): string {
  if (reason.startsWith('no delivery receipt')) return 'no_receipt';
  const m = reason.match(/^(\d{3,6})\b/);
  return m ? m[1]! : reason;
}
export function reasonLabel(reason: string): string {
  const key = `reasonCode.${reasonCode(reason)}`;
  return has(key) ? t(key) : reason;
}
